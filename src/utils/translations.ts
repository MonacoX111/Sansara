export const getMatchStageLabel = (stage: string | undefined, lang: Lang) => {
  if (!stage) return "";

  const normalized = stage.trim().toLowerCase();
  const labels: Record<Lang, Record<string, string>> = {
    en: {
      group: "Group",
      playoff: "Playoff",
      final: "Final",
      showmatch: "Showmatch",
    },
    ua: {
      group: "Групи",
      playoff: "Плей-оф",
      final: "Фінал",
      showmatch: "Шоу-матч",
    },
  };

  return labels[lang]?.[normalized] || titleCaseLabel(stage);
};

