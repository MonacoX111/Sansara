const titleCaseLabel = (value: string) =>
  value
    .replace(/[_-]+/g, " ")
    .replace(/\s*\+\s*/g, " + ")
    .trim()
    .split(/\s+/)
    .map((part) =>
      part === "+"
        ? part
        : part.charAt(0).toUpperCase() + part.slice(1).toLowerCase()
    )
    .join(" ");

